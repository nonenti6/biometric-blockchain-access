-- создание базы данных
BEGIN;

CREATE TABLE IF NOT EXISTS employees (
    employee_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name VARCHAR(150) NOT NULL,
    department VARCHAR(100) NOT NULL,
    fingerprint_template BYTEA NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT employees_fingerprint_unique UNIQUE (fingerprint_template),
    CONSTRAINT employees_name_nonempty CHECK (length(btrim(full_name)) > 0),
    CONSTRAINT employees_fingerprint_nonempty CHECK (octet_length(fingerprint_template) > 0)
);

CREATE TABLE IF NOT EXISTS blocks (
    block_id BIGINT PRIMARY KEY,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    previous_hash CHAR(64) NOT NULL,
    merkle_root CHAR(64) NOT NULL,
    block_hash CHAR(64) NOT NULL UNIQUE,
    transactions_count INTEGER NOT NULL DEFAULT 0,
    CONSTRAINT blocks_count_nonnegative CHECK (transactions_count >= 0),
    CONSTRAINT blocks_hash_format CHECK (
        previous_hash ~ '^[0-9a-f]{64}$'
        AND merkle_root ~ '^[0-9a-f]{64}$'
        AND block_hash ~ '^[0-9a-f]{64}$'
    )
);

CREATE TABLE IF NOT EXISTS transactions (
    transaction_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_id BIGINT NOT NULL REFERENCES employees(employee_id) ON DELETE RESTRICT,
    employee_name VARCHAR(150) NOT NULL,
    fingerprint_hash CHAR(64) NOT NULL,
    passed_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    transaction_hash CHAR(64) NOT NULL,
    block_id BIGINT REFERENCES blocks(block_id) ON DELETE RESTRICT,
    CONSTRAINT transactions_hash_format CHECK (
        fingerprint_hash ~ '^[0-9a-f]{64}$'
        AND transaction_hash ~ '^[0-9a-f]{64}$'
    )
);

CREATE TABLE IF NOT EXISTS block_transactions (
    block_id BIGINT NOT NULL REFERENCES blocks(block_id) ON DELETE RESTRICT,
    transaction_id BIGINT NOT NULL UNIQUE REFERENCES transactions(transaction_id) ON DELETE RESTRICT,
    position_in_block INTEGER NOT NULL,
    recorded_transaction_hash CHAR(64) NOT NULL,
    PRIMARY KEY (block_id, position_in_block),
    CONSTRAINT block_transactions_position_nonnegative CHECK (position_in_block >= 0),
    CONSTRAINT block_transactions_hash_format CHECK (recorded_transaction_hash ~ '^[0-9a-f]{64}$')
);

CREATE INDEX IF NOT EXISTS idx_transactions_pending
    ON transactions (transaction_id) WHERE block_id IS NULL;
CREATE INDEX IF NOT EXISTS idx_transactions_employee_time
    ON transactions (employee_id, passed_at DESC);
CREATE INDEX IF NOT EXISTS idx_transactions_block
    ON transactions (block_id);


